export function PrintDocument() {
  const { id = '' } = useParams()
  const lang = useLang()
  const [doc, setDoc] = useState<QDocument | null>(null)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    api.document(id).then(setDoc, (e: Error) => setError(e.message))
  }, [id])

  useEffect(() => {
    if (doc?.payload?.number) document.title = `${doc.payload.number} — QB`
  }, [doc])

  if (error) return <p className="error" style={{ padding: 24 }}>{error}</p>
  if (!doc?.payload) return <p style={{ padding: 24 }}>…</p>
  return (
    <div className="print-wrap">
      <PrintBar lang={lang} />
      <Sheet doc={doc} lang={lang} />
    </div>
  )
}

/** Several documents in one print job (from the Documents page): each starts on a new page. */
export function PrintBatch() {
  const lang = useLang()
  const [docs, setDocs] = useState<QDocument[] | null>(null)
  const [error, setError] = useState<string | null>(null)
  const ids = new URLSearchParams(window.location.search).get('ids') ?? ''

  useEffect(() => {
    const list = ids.split(',').filter(Boolean).slice(0, 100)
    Promise.all(list.map((id) => api.document(id))).then(setDocs, (e: Error) => setError(e.message))
  }, [ids])

  useEffect(() => {
    document.title = 'QB — documents'
  }, [])

  if (error) return <p className="error" style={{ padding: 24 }}>{error}</p>
  if (!docs) return <p style={{ padding: 24 }}>…</p>
  return (
    <div className="print-wrap">
      <PrintBar lang={lang} />
      {docs
        .filter((d) => d.payload)
        .map((d) => (
          <Sheet key={d.id} doc={d} lang={lang} />
        ))}
    </div>
  )
}

function PrintBar({ lang }: { lang: Lang }) {
  return (
    <div className="no-print print-bar">
      <button className="btn primary" onClick={() => window.print()}>
        {L.print[lang]}
      </button>
    </div>
  )
}

function Sheet({ doc, lang }: { doc: QDocument; lang: Lang }) {
  const p = doc.payload!
  // Label: Armenian first, the reader's language under it (once, if it differs)
  const lb = (k: string) => (
    <>
      {L[k].hy}
      {lang !== 'hy' && <small> {L[k][lang]}</small>}
    </>
  )

  return (
      <article className="a4">
        <header className="a4-head">
          <div>
            <h1>{p.title.hy}</h1>
            {lang !== 'hy' && <div className="a4-sub">{tr(p.title, lang)}</div>}
          </div>
          <table className="a4-meta">
            <tbody>
              <tr><th>{lb('no')}</th><td><b>{p.number}</b></td></tr>
              <tr><th>{lb('date')}</th><td>{p.date}</td></tr>
              <tr><th>{lb('order')}</th><td>{p.order_number}</td></tr>
              {p.delivery_date && <tr><th>{lb('delivery')}</th><td>{p.delivery_date}</td></tr>}
            </tbody>
          </table>
        </header>

        <section className="a4-parties">
          {p.seller && <PartyBox title={lb('seller')} party={p.seller} lb={lb} withBank />}
          {p.buyer && <PartyBox title={lb('buyer')} party={p.buyer} lb={lb} extra={p.delivery_address ? [lb('deliver_to'), p.delivery_address] : undefined} />}
        </section>

        {p.transport && (
          <section className="a4-box">
            <h3>{lb('transport')}</h3>
            <table className="a4-kv">
              <tbody>
                <tr><th>{lb('from')}</th><td>{p.transport.from ?? ''}</td></tr>
                <tr><th>{lb('to')}</th><td>{p.transport.to ?? ''}</td></tr>
                {p.transport.receiver && <tr><th>{lb('receiver')}</th><td>{p.transport.receiver}</td></tr>}
                <tr><th>{lb('vehicle')}</th><td className="blank">{p.transport.vehicle ?? ''}</td></tr>
                <tr><th>{lb('driver')}</th><td className="blank">{p.transport.driver ?? ''}</td></tr>
              </tbody>
            </table>
          </section>
        )}

        <table className="a4-lines">
          <thead>
            <tr>
              <th>№</th>
              <th className="l">{lb('name')}</th>
              <th>{lb('unit')}</th>
              {p.kind === 'acceptance_act' && <th>{lb('confirmed')}</th>}
              <th>{p.kind === 'acceptance_act' ? lb('received') : lb('qty')}</th>
              <th>{lb('price')}</th>
              <th>{lb('amount')}</th>
              <th>{lb('vat')}</th>
            </tr>
          </thead>
          <tbody>
            {p.lines?.map((l) => (
              <tr key={l.n}>
                <td>{l.n}</td>
                <td className="l">
                  {l.name.hy ?? tr(l.name, lang)}
                  {lang !== 'hy' && l.name[lang] && <small> {l.name[lang]}</small>}
                </td>
                <td>{unit(l.unit, 'hy')}</td>
                {p.kind === 'acceptance_act' && <td>{qty(l.qty_confirmed ?? l.qty)}</td>}
                <td className={p.kind === 'acceptance_act' && l.qty_confirmed && Number(l.qty) < Number(l.qty_confirmed) ? 'short' : ''}>{qty(l.qty)}</td>
                <td>{amd(l.price_amd)}</td>
                <td>{amd(l.amount_amd)}</td>
                <td>{l.vat_rate_bp ? amd(l.vat_amd) : '—'}</td>
              </tr>
            ))}
          </tbody>
        </table>

        {p.totals && (
          <table className="a4-totals">
            <tbody>
              <tr><th>{lb('subtotal')}</th><td>{amd(p.totals.subtotal_amd)}</td></tr>
              {p.totals.discount_amd > 0 && <tr><th>{lb('discount')}</th><td>−{amd(p.totals.discount_amd)}</td></tr>}
              {p.totals.delivery_fee_amd > 0 && <tr><th>{lb('delivery_fee')}</th><td>{amd(p.totals.delivery_fee_amd)}</td></tr>}
              <tr className="grand"><th>{lb('total')}</th><td>{amd(p.totals.total_amd)}</td></tr>
              <tr><th>{p.vat_note ? lb('not_vat') : lb('incl_vat')}</th><td>{p.vat_note ? '—' : amd(p.totals.vat_amd)}</td></tr>
            </tbody>
          </table>
        )}

        {p.kind !== 'invoice' && (
          <section className="a4-signs">
            <Sign title={lb('handed')} name={p.seller?.director_name} stamp={lb('stamp')} />
            <Sign title={lb('accepted')} name={p.buyer?.director_name} stamp={lb('stamp')} />
          </section>
        )}
        {p.kind === 'invoice' && (
          <section className="a4-signs">
            <Sign title={lb('director')} name={p.seller?.director_name} stamp={lb('stamp')} />
          </section>
        )}
        <footer className="a4-foot">{L.footer.hy}{lang !== 'hy' && <> · {L.footer[lang]}</>}</footer>
      </article>
  )
}

function PartyBox({
  title,
  party,
  lb,
  withBank,
  extra,
}: {
  title: React.ReactNode
  party: Party
  lb: (k: string) => React.ReactNode
  withBank?: boolean
  extra?: [React.ReactNode, string]
}) {
  return (
    <div className="a4-box">
      <h3>{title}</h3>
      <div className="a4-name">{party.legal_name}</div>
      <table className="a4-kv">
        <tbody>
          <tr><th>{lb('tin')}</th><td>{party.tin}</td></tr>
          {party.registration_number && <tr><th>{lb('reg')}</th><td>{party.registration_number}</td></tr>}
          <tr><th>{lb('address')}</th><td>{party.legal_address}</td></tr>
          {withBank && <tr><th>{lb('bank')}</th><td>{[party.bank_name, party.bank_account].filter(Boolean).join(', ')}</td></tr>}
          {party.director_name && <tr><th>{lb('director')}</th><td>{party.director_name}</td></tr>}
          {extra && <tr><th>{extra[0]}</th><td>{extra[1]}</td></tr>}
        </tbody>
      </table>
    </div>
  )
}

function Sign({ title, name, stamp }: { title: React.ReactNode; name?: string | null; stamp: React.ReactNode }) {
  return (
    <div className="a4-sign">
      <div className="a4-sign-title">{title}</div>
      <div className="a4-sign-line" />
      <div className="a4-sign-name">{name ?? ''}</div>
      <div className="a4-stamp">{stamp}</div>
    </div>
  )
}

